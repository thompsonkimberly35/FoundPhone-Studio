import { ALD1_SECRET_ADMIRER_MEMBERS, isAdultMember, secureRandomIndex } from "./kakaoSecretAdmirer";

export type TeamConflictChoice = { key: string; text: string; next: string };
export type TeamConflictNode = { id: string; lines: string[]; choices: TeamConflictChoice[]; result?: string };
const node = (id: string, line: string, targets: string[], result = ""): TeamConflictNode => ({
  id,
  lines: [line],
  choices: targets.map((next, index) => ({
    key: ["A", "B", "C"][index],
    text: [
      "我想知道你真正的想法。",
      "我不能接受你把自己的选择强加给我们。",
      "我们先冷静一下，再继续谈。",
    ][index],
    next,
  })),
  ...(result ? { result } : {}),
});

// B is selected only after A has been persisted. Unknown birth dates are never treated as adult.
export function getTeamConflictCandidates(boyfriendId: string, friendId: string, admirerId: string, asOf = new Date()) {
  if (!boyfriendId || !friendId || !admirerId) return [];
  return ALD1_SECRET_ADMIRER_MEMBERS.filter(member =>
    member.id !== boyfriendId && member.id !== friendId && member.id !== admirerId &&
    /^\d{4}-\d{2}-\d{2}$/.test(member.birthDate) && isAdultMember(member, asOf)
  );
}
export function chooseTeamConflictMember(boyfriendId: string, friendId: string, admirerId: string, getRandomValues?: (array: Uint32Array) => Uint32Array) {
  const candidates = getTeamConflictCandidates(boyfriendId, friendId, admirerId);
  return candidates.length ? candidates[secureRandomIndex(candidates.length, getRandomValues)] : null;
}

