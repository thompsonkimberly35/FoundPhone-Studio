export function validateTeamConflictStory(): string[] {
  const errors: string[] = [];
  const nodeIds = new Set(Object.keys(TEAM_CONFLICT_STORY).filter(id => id.startsWith("B")));
  const resultIds = new Set(Array.from({ length: 12 }, (_, index) => "S" + String(index + 1).padStart(2, "0")));
  for (const [id, entry] of Object.entries(TEAM_CONFLICT_STORY)) {
    if (id.startsWith("B") && entry.choices.length !== 3) errors.push(id + ": 必须有三个原始选项");
    for (const choice of entry.choices) {
      if (!nodeIds.has(choice.next) && !resultIds.has(choice.next)) errors.push(id + ": 不存在的目标 " + choice.next);
    }
  }
  for (const id of nodeIds) if (!authoredChoices[id]) errors.push(id + ": 缺少原始选项文本");
  const canReachEnding = (id: string, visiting = new Set<string>()): boolean => {
    if (resultIds.has(id)) return true;
    if (!nodeIds.has(id) || visiting.has(id)) return false;
    const nextVisiting = new Set(visiting);
    nextVisiting.add(id);
    return (TEAM_CONFLICT_STORY[id]?.choices || []).some(choice => canReachEnding(choice.next, nextVisiting));
  };
  for (const id of nodeIds) if (!canReachEnding(id)) errors.push(id + ": 无法到达任何阶段性结果");
  return errors;
}
