export function createInstagramBacklash(time: string): Item[] {
  return backlash.map(([handle, body], index) => makeItem({
    id: `ig-backlash-${index + 1}`,
    title: handle,
    sender: handle,
    body,
    time,
    folder: "私信",
    read: false,
    outgoing: false,
    avatar: "",
    meta: { handle, platform: "instagram", sequence: String(index + 1) },
  }));
}

export function instagramNotification(item: Item, index: number) {
  return { id: item.id, handle: item.sender, body: item.body, index };
}
