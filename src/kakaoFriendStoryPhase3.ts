export function getFriendPhase3Choice(nodeId: string, key: string, context: FriendPhase3Context = {}): FriendPhase3Choice | undefined {
  const node = FRIEND_PHASE3_STORY[nodeId];
  const choice = node?.choices.find(entry => entry.key === key);
  if (!choice) return undefined;
  if (nodeId === "F108") {
    if (key === "A") {
      if (context.aOutcome === "R12") return { ...choice, text: "我已经拒绝他了。" };
      if (context.aOutcome === "R13") return { ...choice, text: "我已经决定和他保持距离了。" };
      if (context.aOutcome === "R16") return { ...choice, text: "他之前越过界线，我现在不太信任他。" };
      return undefined;
    }
    if (key === "B" && ["R12", "R13", "R16"].includes(context.aOutcome || "")) return undefined;
  }
  if (nodeId === "F112" && key === "A" && context.aOutcome === "R12") {
    return { ...choice, text: "我没有接受他的告白。" };
  }
  if (nodeId === "F112" && key === "A" && context.aOutcome === "R13") {
    return { ...choice, text: "我已经和他保持距离了。" };
  }
  if (nodeId === "F112" && key === "A" && context.aOutcome === "R16") {
    return { ...choice, text: "我不会接受他越过界线的行为。" };
  }
  return choice;
}

